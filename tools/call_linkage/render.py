def markdown_report(
    graph: CallGraph,
    chains: List[Chain],
    checks: List[Dict[str, str]],
    meta: Dict[str, Any],
    hot: List[Dict[str, Any]],
) -> str:
    stats = graph.stats()
    out: List[str] = []
    out.append("# Call linkage (สายการเรียก) — rebuilt report")
    out.append("")
    out.append(f"_generated by `tools/build_call_linkage.py` from `{meta.get('bundle')}`"
               f" (fingerprint `{meta.get('bundle_fingerprint')}`,"
               f" {meta.get('bundle_files')} files)_")
    out.append("")
    out.append("## Summary")
    out.append("")
    out.append(f"- **{stats['edges']} hops**, **{stats['nodes']} nodes**,"
               f" **{len(chains)} chains**")
    out.append(f"- confidence: " + ", ".join(f"{k}={v}" for k, v in sorted(stats["by_confidence"].items())))
    out.append("")
    out.append("| layer | what it covers | hops |")
    out.append("|---|---|---|")
    for layer in ("L1", "L2", "L3", "L4", "L5", "L6"):
        out.append(f"| `{layer}` {LAYERS[layer]['name']} |"
                   f" {LAYERS[layer]['description']} | {stats['by_layer'].get(layer, 0)} |")
    out.append("")
    out.append("| chain | title | layers | hops |")
    out.append("|---|---|---|---|")
    for c in chains:
        title = c.title_th or c.title
        out.append(f"| `{c.id}` | {title} | {c.layer_path} | {len(c.hops)} |")
    out.append("")
    out.append("```mermaid")
    out.append(OVERVIEW_MERMAID.rstrip("\n"))
    out.append("```")
    out.append("")
    for c in chains:
        out.append(f"## `{c.id}` — {c.title_th or c.title}")
        out.append("")
        out.append(f"*{c.layer_path}* · {len(c.hops)} hops")
        out.append("")
        if c.goal:
            out.append(c.goal)
            out.append("")
        out.append("| # | caller | instruction | callee | conf. | hop note |")
        out.append("|---|---|---|---|---|---|")
        for h in c.hops:
            e = graph.by_id.get(h.edge_id)
            if e is None:
                out.append(f"| {h.n} | — | — | — | — | {h.text} **[UNRESOLVED]** |")
                continue
            caller = f"`{e.src_module}`+`{e.src_offset}`" if e.src_offset else f"`{e.src_module}`"
            callee = f"`{e.dst_module}`+`{e.dst_offset}`" if e.dst_offset else f"`{e.dst_module}`"
            out.append(f"| {h.n} | {caller} | `{e.src_insn[:80]}` | {callee} |"
                       f" {e.confidence} | {h.text} |")
        out.append("")
        out.append("```mermaid")
        out.append(mermaid_chain(c, graph).rstrip("\n"))
        out.append("```")
        out.append("")
    out.append("## Hottest Dart targets (fan-in)")
    out.append("")
    out.append("| target | fan-in | name |")
    out.append("|---|---|---|")
    for t in hot[:25]:
        out.append(f"| `{t['module']}`+`{t['offset']}` | {t['fan_in']} | {t['name']} |")
    out.append("")
    out.append("## Verification")
    out.append("")
    out.append("| result | check | detail |")
    out.append("|---|---|---|")
    for r in checks:
        out.append(f"| {r['status']} | {r['name']} | {r['detail'][:220]} |")
    out.append("")
    kinds = Counter((e.layer, e.kind) for e in graph.edges)
    out.append("## Edge kinds")
    out.append("")
    out.append("| kind | meaning | count |")
    out.append("|---|---|---|")
    for (layer, kind), n in sorted(kinds.items()):
        out.append(f"| `{kind}` ({layer}) | {KINDS[kind]} | {n} |")
    out.append("")
    return "\n".join(out)


