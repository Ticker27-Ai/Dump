def compare_edges(new: List[Edge], old: List[Edge]) -> Dict[str, Any]:
    new_keys = {e.key(): e.edge_id for e in new}
    old_keys = {e.key(): e.edge_id for e in old}
    only_new = sorted(set(new_keys) - set(old_keys))
    only_old = sorted(set(old_keys) - set(new_keys))
    return {
        "new_total": len(new),
        "old_total": len(old),
        "only_in_new": [{"key": list(k), "edge_id": new_keys[k]} for k in only_new],
        "only_in_old": [{"key": list(k), "edge_id": old_keys[k]} for k in only_old],
    }
