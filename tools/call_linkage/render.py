def _short(node_id: str, maxlen: int = 44) -> str:
    s = node_id.replace('"', "'")
    return s if len(s) <= maxlen else s[: maxlen - 1] + "…"


def mermaid_chain(chain: Chain, graph: CallGraph) -> str:
    """Linear flowchart of one resolved chain."""
    lines = ["flowchart LR"]
    for h in chain.hops:
        e = graph.by_id.get(h.edge_id)
        if e is None:
            lines.append(f"    H{h.n}[\"hop {h.n}: UNRESOLVED<br/>{h.text[:60]}\"]")
            continue
        src = _short(node_id_for(e.src_module, e.src_name, e.src_offset))
        dst = _short(node_id_for(e.dst_module, e.dst_name, e.dst_offset))
        label = (e.src_insn or e.kind).replace('"', "'")[:60]
        lines.append(f"    {e.edge_id}S[\"{src}\"] -->|\"{e.edge_id} {label}\"| {e.edge_id}D[\"{dst}\"]")
    return "\n".join(lines) + "\n"


